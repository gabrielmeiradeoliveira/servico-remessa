CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    tipo VARCHAR(2) NOT NULL,
    cpf VARCHAR(11) UNIQUE,
    cnpj VARCHAR(14) UNIQUE,

    CONSTRAINT chk_usuario_tipo  CHECK (tipo IN ('PF', 'PJ')),
    CONSTRAINT chk_usuario_documento CHECK ((tipo = 'PF' AND cpf IS NOT NULL AND cnpj IS NULL) OR
    (tipo = 'PJ' AND cnpj IS NOT NULL AND cpf IS NULL))
);

CREATE TABLE carteira (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    saldo_real DECIMAL NOT NULL DEFAULT 0,
    saldo_dolar DECIMAL NOT NULL DEFAULT 0,

    CONSTRAINT uk_carteira_usuario UNIQUE (usuario_id),
    CONSTRAINT fk_carteira_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id),
    CONSTRAINT chk_carteira_saldo_real CHECK (saldo_real >= 0),
    CONSTRAINT chk_carteira_saldo_dolar CHECK (saldo_dolar >= 0)
);


CREATE TABLE remessa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    remetente_id BIGINT NOT NULL,
    destinatario_id BIGINT NOT NULL,
    valor_real DECIMAL NOT NULL,
    valor_dolar DECIMAL NOT NULL,
    cotacao DECIMAL NOT NULL,
    data_hora TIMESTAMP NOT NULL,
    STATUS VARCHAR(15) NOT NULL,

    CONSTRAINT fk_remessa_remetente FOREIGN KEY (remetente_id) REFERENCES usuario(id),
    CONSTRAINT fk_remessa_destinatario FOREIGN KEY (destinatario_id) REFERENCES usuario(id),
    CONSTRAINT chk_remessa_valor_real CHECK (valor_real > 0),
    CONSTRAINT chk_remessa_valor_dolar  CHECK (valor_dolar > 0),
    CONSTRAINT chk_remessa_cotacao CHECK (cotacao > 0),
    CONSTRAINT chk_remessa_status CHECK (status IN ('PENDENTE', 'CONCLUIDA', 'CANCELADA')),
    CONSTRAINT chk_remessa_usuarios CHECK (remetente_id <> destinatario_id)
);